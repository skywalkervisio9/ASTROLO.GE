export interface CitySeed { label: string; country: string; en: string; lat: number; lng: number; cc: string; }

/** Prefix-match the local city seed (Georgian script + English). Mirrors getGeoSeed() in the runtime. */
export function getCitySeed(q: string, lang: 'ka' | 'en'): CitySeed[] {
  const ql = q.toLowerCase();
  return GEO_CITIES.filter((c) => c.ka.startsWith(q) || c.en.toLowerCase().startsWith(ql)).map((c) => {
    const label = lang === 'ka' ? c.ka : c.en;
    const country = lang === 'ka' ? (KA_COUNTRIES[c.cc] || c.cc) : (EN_COUNTRIES[c.cc] || c.cc);
    return { label, country, en: c.en, lat: c.lat, lng: c.lng, cc: c.cc };
  });
}
